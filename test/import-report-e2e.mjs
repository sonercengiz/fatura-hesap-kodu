import { chromium } from 'playwright';
import { readdirSync, writeFileSync, copyFileSync, readFileSync } from 'node:fs';
import { FIXTURES, SCRATCH, XML_DIR } from './paths.mjs';
const S=SCRATCH;
const P=FIXTURES;
const files=readdirSync(XML_DIR).filter(f=>f.endsWith('.xml')).sort().map(f=>XML_DIR+'/'+f).slice(0,5);
writeFileSync(`${S}/yarim.xml`, files.length ? readFileSync(files[0],'utf8').slice(0, 3000) : '<Invoice>');
writeFileSync(`${S}/not.txt`, 'x'); copyFileSync(files[1], `${S}/kopya.xml`);
const browser=await chromium.launch({channel: process.env.PW_CHANNEL ?? 'chrome',headless:true});
const page=await (await browser.newContext({viewport:{width:1400,height:900}})).newPage();
await page.addInitScript(()=>{try{localStorage.setItem('guideSeen','1')}catch{}});
await page.goto('http://localhost:5179/'); await page.waitForSelector('.welcome');
await page.locator('input[accept*=".zip"]').setInputFiles([...files, `${S}/kopya.xml`, `${P}/irsaliye.xml`, `${P}/bozuk.xml`, `${S}/yarim.xml`, `${S}/not.txt`]);
await page.waitForSelector('.modal:has-text("Yükleme sonucu")',{timeout:30000});
console.log('başlık:', await page.locator('.modal-head .muted').innerText());
console.log((await page.locator('.report-row').allInnerTexts()).map(t=>t.replace(/\s+/g,' ')).join('\n'));
await page.screenshot({path:`${S}/shots/report.png`});
await page.keyboard.press('Escape'); await page.waitForTimeout(100);
console.log('kapandı:', await page.locator('.modal').count()===0, '| yüklenen:', await page.locator('.progress').innerText());
await browser.close();
